from kneed import KneeLocator
z= KneeLocator(range(1, 11), WCSS, curve='convex', direction='decreasing')
otimal_cluster = z.elbow
print(f"The Clusters' optimal number is as follows: {otimal_cluster}")

kmeans= KMeans(n_clusters=otimal_cluster, init='k-means++', random_state=42)
CLUSTER= kmeans.fit_predict(data_scaled)

data['cluster'] = CLUSTER

#PLOT THE CLUSTERS
plt.figure(figsize=(13,9))
sns.scatterplot(x='income', y='spending_score', hue='cluster', data=data, palette=sns.color_palette('husl',4), s=100, alpha=0.8)

#add the centriods
centroids = x.inverse_transform(kmeans.cluster_centers_)
plt.scatter(centroids[:, 0], centroids[:, 1], marker= 'X', s=250, alpha=0.8, c='hotpink', label='Centroids', edgecolor='red', linewidth=2)
plt.xlabel('Income')
plt.ylabel('Score of Spending')
plt.title(f'Customer Segmentation Graph (k=4)')
plt.legend()
plt.grid(True, alpha=0.5)
plt.show()

