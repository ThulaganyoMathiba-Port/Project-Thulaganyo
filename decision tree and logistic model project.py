#evaluate the perfomance of the model
accuracy_rfe = accuracy_score(Y_test, y_pred_rfe)
print("Accuracy:", accuracy_rfe)
print("Classification Report:\n", classification_report(Y_test, y_pred_rfe))
print('\nConfusion Matrix" \n)', confusion_matrix(Y_test, y_pred_rfe))

